export function getPredefinedCharactersByEra(
  era: string
): PredefinedCharacter[] {
  if (
    era === 'gaslight' ||
    era === 'classic' ||
    era === 'modern' ||
    era === 'prl-1970s' ||
    era === '1990s' ||
    era === '2000s'
  ) {
    return PREDEFINED_CHARACTERS.filter((character) => character.era === era);
  }
  return [];
}
